import { test, expect } from '@playwright/test';
import { A, B, groupId, profile, state, backend, login } from './trip-fixtures.mjs';
import { passportFixture } from './passport-fixtures.mjs';

const button = (page, name) => page.getByRole('button', { name, exact: true });
for (const width of [320, 390]) test(`passport collection, thresholds and level work at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 });
  const store = state();
  store.passports.set(A, passportFixture(groupId(A), { profile: 1, active_days: 7, messages: 49, plans: 1 }));
  await backend(page.context(), store); await login(page);
  await page.getByRole('tab', { name: 'Profil', exact: true }).click();
  const section = page.getByTestId('passport-profile-section');
  await expect(section.getByText('Paszport podróżnika', { exact: true })).toBeVisible();
  await expect(section.getByText('5 z 53 odznak', { exact: true })).toBeVisible();
  await expect(page.getByTestId('passport-level-' + groupId(A))).toContainText('Poziom 2 · W drodze');
  await button(page, 'Edytuj profil').click();
  await expect(page.getByRole('heading', { name: 'Edytuj profil', exact: true })).toBeVisible();
  await page.screenshot({ path: `.expo/passport-${width}-reference-edit-profile.png` });
  await button(page, 'Wróć do profilu').click();
  await button(page, 'Otwórz paszport').click();
  await expect(page).toHaveURL(/\/traveler-passport$/);
  await page.screenshot({ path: `.expo/passport-${width}-header.png` });
  await expect(page.getByTestId('passport-badge-messages')).toContainText('49 / 50');
  await page.getByTestId('passport-badge-messages').click();
  const dialog = page.getByRole('dialog', { name: 'Rozmówca' });
  await expect(dialog.getByText('Brąz · próg 10', { exact: true })).toBeVisible();
  await expect(dialog.getByText('Srebro · próg 50', { exact: true })).toBeVisible();
  await expect(dialog.getByText('Twój postęp: 49 · wiadomości', { exact: true })).toBeVisible();
  await button(dialog, 'Gotowe').click();
  await button(page, 'Zdobyte').click();
  await expect(page.getByTestId('passport-badge-ideas')).toHaveCount(0);
  await expect(page.getByTestId('passport-badge-messages')).toBeVisible();
  await page.screenshot({ path: `.expo/passport-${width}-collection.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
test('new awards sync without duplicate celebrations and another account gets its own passport', async ({ page }) => {
  const store = state();store.passports.set(A, passportFixture(groupId(A), { messages: 9, active_days: 1 }));
  await backend(page.context(), store);await login(page);
  await expect.poll(() => store.passportCalls?.length ?? 0).toBeGreaterThan(0);
  await expect(page.getByTestId('passport-award-notice')).toHaveCount(0);
  store.passports.set(A, passportFixture(groupId(A), { messages: 10, active_days: 1 }));
  await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await expect(page.getByTestId('passport-award-notice')).toContainText('Rozmówca · Brąz');
  await button(page, 'Zamknij informację o odznace').click();
  await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await expect(page.getByTestId('passport-award-notice')).toHaveCount(0);
  await page.goto('/settings');await button(page, 'Wyloguj się').click();await login(page, 'b@example.com');
  await page.goto('/traveler-passport');
  await expect(page.getByTestId('passport-badge-messages')).toContainText('0 / 10');
  await expect(page.getByText('1 z 53 odznak', { exact: true })).toBeVisible();
});
test('load failure can be retried and public passport shows awards without activity counters', async ({ page }) => {
  const store = state();store.failPassport = true;
  store.passports.set(B, passportFixture(groupId(B), { messages: 200, plans: 5, active_days: 7 }));
  await backend(page.context(), store);await login(page);await page.goto('/traveler-passport');
  await expect(page.getByText('Nie udało się wczytać paszportu. Sprawdź połączenie i spróbuj ponownie.', { exact: true })).toBeVisible();
  store.failPassport = false;await button(page, 'Spróbuj ponownie').click();
  await expect(page.getByText('1 z 53 odznak', { exact: true })).toBeVisible();
  await page.goto('/traveler-passport?groupId=' + groupId(B) + '&name=Ekipa%20B');
  await expect(page.getByTestId('passport-badge-messages')).toContainText('Złoto');
  await page.getByTestId('passport-badge-messages').click();
  const dialog = page.getByRole('dialog', { name: 'Rozmówca' });
  await expect(dialog.getByText(/Twój postęp/)).toHaveCount(0);
  await expect(dialog.getByText('Złoto · próg 200', { exact: true })).toBeVisible();
  await button(dialog, 'Gotowe').click();
  await page.screenshot({ path: '.expo/passport-public.png', fullPage: true });
});
