import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { parseEnv } from 'node:util';

const local = process.argv.includes('--local');
const check = process.argv.includes('--check');
const ref = 'kswuakzcnoqgovnwejhb';
if (!local) {
  const env = parseEnv(readFileSync('.env.local', 'utf8'));
  if (new URL(env.EXPO_PUBLIC_SUPABASE_URL).hostname !== ref + '.supabase.co')
    throw Error('Dev project mismatch');
}
const cli = process.env.npm_execpath
  ? join(dirname(process.env.npm_execpath), 'npx-cli.js')
  : join(dirname(process.execPath), 'node_modules/npm/bin/npx-cli.js');
const args = [
  '--yes',
  'supabase@2.122.0',
  'gen',
  'types',
  'typescript',
  '--schema',
  'public',
  ...(local ? ['--local'] : ['--project-id', ref]),
];
const result = spawnSync(process.execPath, [cli, ...args], {
  encoding: 'utf8',
  windowsHide: true,
  timeout: 60000,
  maxBuffer: 5_000_000,
});
if (result.status !== 0 || !result.stdout.includes('export type Database'))
  throw Error('Cannot generate database types; raw diagnostics suppressed');
const header =
  '// Generated by npm run types:database. Do not edit. JSON RPC contracts are validated separately.\n';
const text = header + result.stdout.replaceAll('\r\n', '\n').trim() + '\n';
const file = 'src/types/database.generated.ts';
if (check) {
  if (readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== text)
    throw Error(
      'Database types differ. Regenerate after migrating the local database.',
    );
  console.log('Database schema types match.');
} else {
  writeFileSync(file, text);
  console.log(
    'Generated public schema types (' + (local ? 'local' : 'Dev') + ').',
  );
}
