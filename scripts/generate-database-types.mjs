import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import {
  firstTypeDifference,
  schemaTypeText,
} from './database-type-comparison.mjs';

// The migration database and this pinned CLI are the canonical generator.
// Hosted Management API generation can use a different template version.
if (process.argv.slice(2).some((arg) => !['--local', '--check'].includes(arg)))
  throw Error(
    'Use npm run types:database -- [--local] [--check]. Only the local migration database is supported.',
  );
const check = process.argv.includes('--check');
const cli = process.env.npm_execpath
  ? join(dirname(process.env.npm_execpath), 'npx-cli.js')
  : join(dirname(process.execPath), 'node_modules/npm/bin/npx-cli.js');
const args = [
  '--yes',
  'supabase@2.122.0',
  'gen',
  'types',
  'typescript',
  '--schema',
  'public',
  '--local',
];
const result = spawnSync(process.execPath, [cli, ...args], {
  encoding: 'utf8',
  windowsHide: true,
  timeout: 60000,
  maxBuffer: 5_000_000,
});
if (result.status !== 0 || !result.stdout.includes('export type Database'))
  throw Error('Cannot generate database types; raw diagnostics suppressed');
const header =
  '// Generated by npm run types:database from local migrations. Do not edit.\n';
const text = header + schemaTypeText(result.stdout);
const file = 'src/types/database.generated.ts';
if (check) {
  const difference = firstTypeDifference(readFileSync(file, 'utf8'), text);
  mkdirSync('.expo', { recursive: true });
  writeFileSync('.expo/database.generated.local.ts', text);
  if (difference) {
    console.error('First schema difference: ' + JSON.stringify(difference));
    throw Error(
      'Database types differ. Regenerate after migrating the local database.',
    );
  }
  console.log('Database schema types match.');
} else {
  writeFileSync(file, text);
  console.log('Generated public schema types from local migrations.');
}
