import { readFileSync, writeFileSync } from 'node:fs';
import {
  getLocalities,
  LOCALITY_SOURCE,
} from '../src/data/locations/polish-localities.ts';
import { findTripLocation } from '../src/features/trips/trip-locations.ts';
import { getLocationMapArea } from '../src/features/trips/trip-map-data.ts';

const data = getLocalities();
const points = data.places.map((row) => [
  'pl-locality:' + row[0],
  row[6],
  row[7],
  3000,
  null,
]);
for (const id of [
  ...data.provinces.map((p) => 'pl-region:' + p),
  'country:PL',
  'demo-location-kaszuby',
  'demo-location-sudety',
  'demo-location-bory-tucholskie',
  'demo-location-slowenia',
]) {
  const area = getLocationMapArea(findTripLocation(id));
  if (area) {
    const rows =
      id === 'country:PL'
        ? data.places
        : id.startsWith('pl-region:')
          ? data.places.filter((row) => data.provinces[row[3]] === id.slice(10))
          : [];
    const bounds = rows.length
      ? {
          south: Math.min(...rows.map((r) => r[6])),
          north: Math.max(...rows.map((r) => r[6])),
          west: Math.min(...rows.map((r) => r[7])),
          east: Math.max(...rows.map((r) => r[7])),
        }
      : null;
    points.push([
      id,
      area.latitude,
      area.longitude,
      Math.ceil(area.radiusMeters),
      bounds,
    ]);
  }
}
for (const [alias, id] of [
  ['demo-location-chlapowo', 'pl-locality:4259'],
  ['demo-location-gdansk', 'pl-locality:8457'],
  ['demo-location-polska', 'country:PL'],
]) {
  const row = points.find((p) => p[0] === id);
  if (row) points.push([alias, ...row.slice(1)]);
}
const header = `-- Generated by node scripts/generate-map-locations.mjs; do not edit coordinates by hand.
-- Existing PRNG locality snapshot: ${LOCALITY_SOURCE.repository}, ${LOCALITY_SOURCE.commit}.
-- Provenance and original license: src/data/locations/README.md. Areas are approximate circles.
create table discovery_private.map_locations (
  id text primary key,
  latitude double precision not null check(latitude between -85 and 85),
  longitude double precision not null check(longitude between -180 and 180),
  radius_m double precision not null check(radius_m between 0 and 20000000),
  bounds jsonb
);
alter table discovery_private.map_locations enable row level security;
revoke all on discovery_private.map_locations from public,anon,authenticated;
create index map_locations_position on discovery_private.map_locations(latitude,longitude);
`;
const sql = (value) => "'" + value.replaceAll("'", "''") + "'";
let text = header;
for (let i = 0; i < points.length; i += 500)
  text +=
    'insert into discovery_private.map_locations values\n' +
    points
      .slice(i, i + 500)
      .map(
        ([id, lat, lng, r, bounds]) =>
          `(${sql(id)},${lat},${lng},${r},${bounds ? sql(JSON.stringify(bounds)) + '::jsonb' : 'null'})`,
      )
      .join(',\n') +
    ';\n';
const path = 'supabase/migrations/202611030003_discovery_map_locations.sql';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== text)
    throw Error('Map coordinates differ; regenerate.');
} else writeFileSync(path, text);
console.log(
  `${points.length} map locations verified against the bundled locality dictionary.`,
);
